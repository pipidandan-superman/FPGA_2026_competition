`timescale 1ns/1ps
// t1_preproc_norm.v
// T1 normalization: (x*1000 - mean_milli) x fp32(1/(1000*std)) -- single
// IEEE fp32 multiply, realized with OFFICIAL floating_point 7.1 IPs:
//   t1_fp_i2f  (Fixed_to_float, 18-bit signed integer in, Single out,
//               C_A_WIDTH=18, latency 7, per xci)
//   t1_fp_mul  (Multiply Single x Single -> Single, latency 9, per xci)
// chained AXIS stream: i2f M_AXIS -> mul S_AXIS_A (tvalid/tready/tdata
// wired straight through), mul S_AXIS_B = per-channel constant k,
// mul M_AXIS_RESULT_TREADY tied 1 (result FSM is always ready; no
// backpressure anywhere in this single-stream datapath).
//
// ONE i2f instance + ONE mul instance (per task brief). The three channels
// of each pixel are serialized into the stream (B, G, R) -> 3 cycles/pixel
// issue throughput; results return in order 16 cycles later (7+9).
//
// 18-bit input range caveat (proven by sim probe of the IP model: only
// tdata[17:0] is used, signed, upper 6 bits ignored):
//   d = pix*1000 - mean_milli spans [-123675, +151410], which EXCEEDS the
//   signed 18-bit range [-131072, +131071] for bright pixels
//   (B: pix>=235, G: pix>=248, R: pix==255; 30 (ch,pix) cases).
//   Negative side always fits (d >= -123675). For those 30 bright cases
//   the exact fp32 result is delivered by BRIGHT_LUT (combinational
//   constants, generated by the same numpy float32 formula as
//   tools/gen_ref.py, verified bit-exact in the gates). The wrapped IP
//   output for those beats is discarded. Integration note: regenerating
//   the i2f IP with C_A_WIDTH>=19 (or 24) removes the need for BRIGHT_LUT.
module t1_preproc_norm (
  input  wire        clk,
  input  wire        rstn,
  // pixel input: one scaled pixel; top presents it when in_ready
  input  wire        in_valid,
  output wire        in_ready,
  input  wire [7:0]  in_b,
  input  wire [7:0]  in_g,
  input  wire [7:0]  in_r,
  // result: one output pixel (3 fp32 words), in-order, 1-cycle pulse
  output reg         out_valid,
  output reg  [95:0] out_data    // {fp32 R, fp32 G, fp32 B} = {fr, fg, fb}
);

  // fp32 bit patterns of 1/(1000*std) (BGR), same pin values as gen_ref.py
  localparam [31:0] MEAN_MILLI_B = 32'd103530;
  localparam [31:0] MEAN_MILLI_G = 32'd116280;
  localparam [31:0] MEAN_MILLI_R = 32'd123675;
  localparam [31:0] INV_K_B = 32'h379234e9;
  localparam [31:0] INV_K_G = 32'h3792dc01;
  localparam [31:0] INV_K_R = 32'h378fa721;

  // ------------------------------------------------------------------
  // issue FSM: latch input pixel, serialize B,G,R into the i2f stream
  // ------------------------------------------------------------------
  localparam IS_IDLE = 1'b0,
             IS_ISSUE = 1'b1;

  reg        is_state;
  reg [7:0]  pix_b, pix_g, pix_r;   // latched input pixel
  reg [1:0]  ch_is;                 // issue channel 0,1,2

  assign in_ready = (is_state == IS_IDLE);

  // d = pix*1000 - mean_milli[ch]  (signed, 19 bits enough: |d| <= 151410)
  // pix*1000 = pix<<10 - pix<<4 - pix<<3   (1024 - 16 - 8 = 1000)
  reg [18:0] d_ch;
  always @(*) begin
    case (ch_is)
      2'd1:    d_ch = {1'b0, pix_g, 10'b0} - {1'b0, pix_g, 4'b0}
                      - {1'b0, pix_g, 3'b0} - 19'd116280;
      2'd2:    d_ch = {1'b0, pix_r, 10'b0} - {1'b0, pix_r, 4'b0}
                      - {1'b0, pix_r, 3'b0} - 19'd123675;
      default: d_ch = {1'b0, pix_b, 10'b0} - {1'b0, pix_b, 4'b0}
                      - {1'b0, pix_b, 3'b0} - 19'd103530;
    endcase
  end

  // bright: d in [131072, 151410]  <=>  d[18]==0 && d[17]==1
  wire bright_ch = ~d_ch[18] & d_ch[17];

  // ------------------------------------------------------------------
  // FP IP stream wiring
  // ------------------------------------------------------------------
  wire        i2f_in_v  = (is_state == IS_ISSUE);
  wire        i2f_in_r;
  wire [23:0] i2f_in_d  = {{6{d_ch[17]}}, d_ch[17:0]};  // 18-bit signed value
  wire        i2f_out_v, i2f_out_r;
  wire [31:0] i2f_out_f;

  wire        mul_out_v;
  wire [31:0] mul_out_f;

  // channel of the beat currently BETWEEN i2f and mul (for the B operand)
  reg [1:0]  ch_mid;
  reg [31:0] k_mid;
  always @(*) begin
    case (ch_mid)
      2'd1:    k_mid = INV_K_G;
      2'd2:    k_mid = INV_K_R;
      default: k_mid = INV_K_B;
    endcase
  end

  t1_fp_i2f u_i2f (
    .aclk                 (clk),
    .s_axis_a_tvalid      (i2f_in_v),
    .s_axis_a_tready      (i2f_in_r),
    .s_axis_a_tdata       (i2f_in_d),
    .m_axis_result_tvalid (i2f_out_v),
    .m_axis_result_tready (i2f_out_r),
    .m_axis_result_tdata  (i2f_out_f)
  );

  t1_fp_mul u_mul (
    .aclk                 (clk),
    .s_axis_a_tvalid      (i2f_out_v),
    .s_axis_a_tready      (i2f_out_r),
    .s_axis_a_tdata       (i2f_out_f),
    .s_axis_b_tvalid      (i2f_out_v),
    .s_axis_b_tready      (),
    .s_axis_b_tdata       (k_mid),
    .m_axis_result_tvalid (mul_out_v),
    .m_axis_result_tready (1'b1),
    .m_axis_result_tdata  (mul_out_f)
  );

  // ------------------------------------------------------------------
  // sideband pipeline: LAT = 16 stages, shifted EVERY CLOCK CYCLE (not
  // per accepted beat). The FP chain latency is cycle-based (accept
  // edge -> mul m_axis tvalid = 16 cycles, consumed by the result FSM
  // at the next edge, measured 16 cycles accept-to-consume in sim),
  // while the issue FSM is bursty (3 beats per 4 cycles), so a
  // beat-indexed shift register can never stay aligned. Stage 0 loads
  // the accepted beat's flag+pixel, all stages shift unconditionally;
  // the tap at stage LAT-1 presents beat k's data at its consume edge.
  // ------------------------------------------------------------------
  localparam LAT = 16;

  reg [23:0]    pix_pipe [0:LAT-1];
  reg [LAT-1:0] bright_pipe;
  integer pi;

  wire beat_accept = i2f_in_v && i2f_in_r;

  // ------------------------------------------------------------------
  // exact fp32 constants for the 30 bright (channel, pixel) cases
  // fl32((pix*1000 - mean_milli) * fl32(1/(1000*std))), from gen_ref formula
  // ------------------------------------------------------------------
  function [31:0] bright_lut;
    input [1:0] ch;
    input [7:0] pix;
    begin
      bright_lut = 32'h00000000;
      case (ch)
        2'd0: case (pix)
          8'd235: bright_lut = 32'h4012a690;  8'd236: bright_lut = 32'h4013c41f;
          8'd237: bright_lut = 32'h4014e1af;  8'd238: bright_lut = 32'h4015ff3e;
          8'd239: bright_lut = 32'h40171ccd;  8'd240: bright_lut = 32'h40183a5d;
          8'd241: bright_lut = 32'h401957ec;  8'd242: bright_lut = 32'h401a757c;
          8'd243: bright_lut = 32'h401b930b;  8'd244: bright_lut = 32'h401cb09a;
          8'd245: bright_lut = 32'h401dce2a;  8'd246: bright_lut = 32'h401eebb9;
          8'd247: bright_lut = 32'h40200948;  8'd248: bright_lut = 32'h402126d8;
          8'd249: bright_lut = 32'h40224467;  8'd250: bright_lut = 32'h402361f6;
          8'd251: bright_lut = 32'h40247f86;  8'd252: bright_lut = 32'h40259d15;
          8'd253: bright_lut = 32'h4026baa4;  8'd254: bright_lut = 32'h4027d834;
          8'd255: bright_lut = 32'h4028f5c3;
          default: ;
        endcase
        2'd1: case (pix)
          8'd248: bright_lut = 32'h401395df;  8'd249: bright_lut = 32'h4014b4b5;
          8'd250: bright_lut = 32'h4015d38b;  8'd251: bright_lut = 32'h4016f261;
          8'd252: bright_lut = 32'h40181136;  8'd253: bright_lut = 32'h4019300c;
          8'd254: bright_lut = 32'h401a4ee2;  8'd255: bright_lut = 32'h401b6db7;
          default: ;
        endcase
        default: case (pix)
          8'd255: bright_lut = 32'h400fee1d;
          default: ;
        endcase
      endcase
    end
  endfunction

  // ------------------------------------------------------------------
  // result FSM: collect mul beats (in order), assemble pixels
  // ------------------------------------------------------------------
  reg [1:0]  ch_rc;                 // result channel 0,1,2
  reg [31:0] fb, fg, fr;

  wire [23:0] pix_now  = pix_pipe[LAT-1];
  wire        brt_now  = bright_pipe[LAT-1];
  // LUT is indexed by the CURRENT channel's pixel value, not always B
  wire [7:0]  pix_lut  = (ch_rc == 2'd1) ? pix_now[15:8] :
                         (ch_rc == 2'd2) ? pix_now[23:16] : pix_now[7:0];
  wire [31:0] val_now  = brt_now ? bright_lut(ch_rc, pix_lut) : mul_out_f;

  // sideband: cycle-based shift (single owner of pix_pipe/bright_pipe)
  integer si;
  always @(posedge clk or negedge rstn) begin
    if (!rstn) begin
      bright_pipe <= {LAT{1'b0}};
      for (si = 0; si < LAT; si = si + 1)
        pix_pipe[si] <= 24'd0;
    end else begin
      pix_pipe[0]    <= beat_accept ? {pix_r, pix_g, pix_b} : 24'd0;
      bright_pipe[0] <= beat_accept ? bright_ch : 1'b0;
      for (si = 1; si < LAT; si = si + 1) begin
        pix_pipe[si]    <= pix_pipe[si-1];
        bright_pipe[si] <= bright_pipe[si-1];
      end
    end
  end

  always @(posedge clk or negedge rstn) begin
    if (!rstn) begin
      is_state    <= IS_IDLE;
      pix_b       <= 8'd0;
      pix_g       <= 8'd0;
      pix_r       <= 8'd0;
      ch_is       <= 2'd0;
      ch_mid      <= 2'd0;
      ch_rc       <= 2'd0;
      fb          <= 32'd0;
      fg          <= 32'd0;
      fr          <= 32'd0;
      out_valid   <= 1'b0;
      out_data    <= 96'd0;
    end else begin
      out_valid <= 1'b0;

      // ---- issue FSM ----
      case (is_state)
        IS_IDLE: begin
          if (in_valid) begin
            pix_b    <= in_b;
            pix_g    <= in_g;
            pix_r    <= in_r;
            ch_is    <= 2'd0;
            is_state <= IS_ISSUE;
          end
        end
        default: begin  // IS_ISSUE
          if (beat_accept) begin
            if (ch_is == 2'd2) begin
              ch_is    <= 2'd0;
              is_state <= IS_IDLE;
            end else begin
              ch_is <= ch_is + 2'd1;
            end
          end
        end
      endcase

      // ---- mid stream: channel tag for the mul B operand ----
      if (i2f_out_v && i2f_out_r)
        ch_mid <= (ch_mid == 2'd2) ? 2'd0 : ch_mid + 2'd1;

      // ---- result FSM ----
      if (mul_out_v) begin
        case (ch_rc)
          2'd0: fb <= val_now;
          2'd1: fg <= val_now;
          default: begin
            fr        <= val_now;
            out_valid <= 1'b1;
            out_data  <= {val_now, fg, fb};   // {fr, fg, fb}
          end
        endcase
        ch_rc <= (ch_rc == 2'd2) ? 2'd0 : ch_rc + 2'd1;
      end
    end
  end

endmodule
